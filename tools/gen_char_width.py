#!/usr/bin/env python3
"""Generates libs/core/src/CharWidthTables.inc from Python's unicodedata module.

Usage: python3 tools/gen_char_width.py > libs/core/src/CharWidthTables.inc

The classification follows Markus Kuhn's wcwidth() (which glibc and most shells also use), so the
terminal and applications agree on cursor positions:
  * zero width: general categories Mn, Me, Cf (except U+00AD SOFT HYPHEN), Hangul Jamo medial
    vowels / final consonants (U+1160-U+11FF, U+D7B0-U+D7FF) and U+200B;
  * double width: East Asian Width W or F (this includes emoji with default emoji presentation);
  * everything else printable: single width.
"""

import sys
import unicodedata


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_zero_width(cp):
    if cp < 0x300:
        return False  # nothing printable below U+0300 is zero width (SHY is kept at width 1)
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF or cp == 0x200B:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F") and not is_zero_width(cp)


def emit(name, table):
    print(f"constexpr Range {name}[] = {{")
    line = "   "
    for first, last in table:
        item = f" {{0x{first:04X}, 0x{last:04X}}},"
        if len(line) + len(item) > 100:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};")
    print()


def main():
    print("// Generated by tools/gen_char_width.py from Unicode "
          f"{unicodedata.unidata_version}. Do not edit by hand.")
    print()
    emit("kZeroWidth", ranges(is_zero_width))
    emit("kWide", ranges(is_wide))
    return 0


if __name__ == "__main__":
    sys.exit(main())
